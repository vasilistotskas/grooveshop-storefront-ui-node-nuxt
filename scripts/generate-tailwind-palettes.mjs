#!/usr/bin/env node
/**
 * Writes `shared/theme/tailwindPalettes.ts`: every palette of the installed
 * Tailwind (`tailwindcss/theme.css`), each shade mapped into sRGB as CSS
 * Color 4 maps it (`shared/utils/oklch.ts`), as `#rrggbb`. The theme's
 * defaults (`shared/theme/defaults.ts`) and the seeding of a store's theme
 * from the Tailwind colour names it uses today read it; a page never does.
 *
 *   pnpm generate:palettes
 *
 * `test/unit/scripts/generate-tailwind-palettes.spec.ts` fails when the
 * committed module is not what this writes (after a Tailwind upgrade): run it
 * again and commit the result.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import { gamutMapToSrgb, hexFromSrgb } from '../shared/utils/oklch.ts'

export const TAILWIND_PALETTES_FILE = fileURLToPath(new URL('../shared/theme/tailwindPalettes.ts', import.meta.url))

const SHADES = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950']
const DECLARATION = /--color-([a-z]+)-(\d+): oklch\(([\d.]+)% ([\d.]+) ([\d.]+|none)\)/g

/** The palettes `css` declares, by name then shade, as `#rrggbb`, names sorted. */
export function tailwindPaletteHexes(css) {
  const palettes = {}
  for (const [, name, shade, lightness, chroma, hue] of css.matchAll(DECLARATION)) {
    palettes[name] = { ...palettes[name], [shade]: { l: Number(lightness) / 100, c: Number(chroma), h: hue === 'none' ? Number.NaN : Number(hue) } }
  }
  return Object.fromEntries(Object.keys(palettes).sort().map(name => [
    name,
    Object.fromEntries(SHADES.map(shade => [shade, hexFromSrgb(gamutMapToSrgb(palettes[name][shade]))])),
  ]))
}

/** The installed Tailwind's `theme.css`. */
export function installedTailwindTheme() {
  return readFileSync(createRequire(import.meta.url).resolve('tailwindcss/theme.css'), 'utf8')
}

/** The module's source for the installed Tailwind. */
export function tailwindPalettesModule() {
  const palettes = tailwindPaletteHexes(installedTailwindTheme())
  const body = Object.entries(palettes).map(([name, scale]) =>
    `  ${name}: { ${Object.entries(scale).map(([shade, hex]) => `${shade}: '${hex}'`).join(', ')} },`,
  ).join('\n')
  return [
    '// Generated by `pnpm generate:palettes` (scripts/generate-tailwind-palettes.mjs) from the',
    '// installed Tailwind. Never edit by hand: run the script again after a Tailwind upgrade.',
    '',
    'import type { ThemeScale } from \'./scale\'',
    '',
    '/** Every Tailwind palette in sRGB, by name: the shades CSS Color 4 gamut mapping gives its OKLCH values. */',
    'export const TAILWIND_PALETTES = {',
    body,
    '} as const satisfies Record<string, ThemeScale>',
    '',
    '/** The name of a Tailwind palette. */',
    'export type TailwindPaletteName = keyof typeof TAILWIND_PALETTES',
    '',
  ].join('\n')
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(TAILWIND_PALETTES_FILE, tailwindPalettesModule())
  process.stdout.write(`wrote ${TAILWIND_PALETTES_FILE}\n`)
}
